function deepMerge(base, overlay) {
  if (overlay === null || overlay === undefined) return base;
  if (typeof overlay !== "object" || Array.isArray(overlay)) return overlay;
  const out = { ...base };
  for (const [k, v] of Object.entries(overlay)) {
    if (v && typeof v === "object" && !Array.isArray(v) && base[k] && typeof base[k] === "object") {
      out[k] = deepMerge(base[k], v);
    } else {
      out[k] = v;
    }
  }
  return out;
}

/** Merge English parcelValues with language-specific common/status maps (full enum coverage). */
function buildParcelValues(commonOverrides, units, auditors, notes, historyLabels) {
  return deepMerge(en.parcelValues, {
    units,
    common: { ...en.parcelValues.common, ...commonOverrides },
    status: {
      active: commonOverrides.active ?? en.parcelValues.status.active,
      mutation_pending: commonOverrides.mutation_pending ?? en.parcelValues.status.mutation_pending,
      disputed: commonOverrides.disputed ?? en.parcelValues.status.disputed,
    },
    varianceBand: {
      green: commonOverrides.green ?? en.parcelValues.varianceBand.green,
      amber: commonOverrides.amber ?? en.parcelValues.varianceBand.amber,
      red: commonOverrides.red ?? en.parcelValues.varianceBand.red,
    },
    auditors,
    notes,
    historyLabels,
    owners: en.parcelValues.owners,
  });
}

